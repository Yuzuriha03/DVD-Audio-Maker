#!/usr/bin/env bash
# ============================================================================
#  DVD-Audio Maker —— 用户配置
#
#  这是唯一需要你修改的文件。所有脚本都会读取它。
#
#  格式：KEY=值        （值可以加引号，也可以用 # 写注释）
#  · 只写「绝对路径」，不要在值里引用其它变量
#    （bash 与 Python 的展开规则不同，混用会出错）
#  · 路径按 **WSL 内** 的写法：Windows 的 D:\Music 要写成 /mnt/d/Music
#  · 另外还有 2 个环境变量可临时覆盖：DVDA_SRC、DVDA_FINAL_DIR
# ============================================================================
#
#
#  ┌────────────────────────────────────────────────────────────────────────┐
#  │  路径示例：只需设置 2 个「必填」路径                                    │
#  └────────────────────────────────────────────────────────────────────────┘
#
#  假设你的音乐放在 Windows 的  D:\Music\MyAlbums\
#  里面按专辑分了子目录：
#
#      D:\Music\MyAlbums\                        <- 让 DVDA_SRC 指向这里
#      ├── Album A (2024)\
#      │   ├── 01. First Song.flac
#      │   ├── 02. Second Song.flac
#      │   └── 03. Third Song.flac
#      ├── Album B (2025)\
#      │   ├── 01. Song One.flac
#      │   └── 02. Song Two.m4a
#      └── Album C - Single\
#          └── 01. Only Song.flac
#
#  对应到 WSL 内就是  /mnt/d/Music/MyAlbums/
#  （c: → /mnt/c，d: → /mnt/d，以此类推；注意斜杠方向）
#
#  输出放哪里：假设想让 ISO 出现在  D:\DVD_Output\
#  对应 WSL 就是  /mnt/d/DVD_Output/
#  该目录**不需要预先创建**，出盘时会自动建。
#
#  于是只需要改这两行：
#
#      DVDA_SRC="/mnt/d/Music/MyAlbums"      # 必填 · 音源根目录
#      DVDA_FINAL_DIR="/mnt/d/DVD_Output"    # 必填 · ISO 输出目录
#
#  工作目录（第 3 项）建议留在 WSL 内部 /root 下 —— 不要放 /mnt/c，
#  否则 MLP 缓存（可达数 GB）会让整个流程慢好几倍。
#
#
#  ┌────────────────────────────────────────────────────────────────────────┐
#  │  对音源的要求                                                          │
#  └────────────────────────────────────────────────────────────────────────┘
#
#  1. 格式：.flac 或 .m4a（ALAC）。递归扫描，深度不限。
#
#  2. 每个文件需要有这些标签，否则分盘顺序与归一化会不准：
#         date    发布日期（如 2024-05-26 或 2024）—— 决定专辑先后顺序
#         track   曲序号（如 1/5 或 01）
#         album   专辑名 —— **同一专辑必须填完全相同的字符串**
#         title   曲名
#     FLAC 与 M4A 的标签通常自带；若缺失，用 foobar2000 / Mp3tag 补。
#
#  3. 采样率与位深可以混用（44.1k / 48k / 96k，16-bit / 24-bit）：
#     脚本会按专辑做归一化 —— 同一专辑内以「多数采样率 + 该采样率下多数
#     位深」为准，少数曲目自动重采样，保证整张专辑能连续播放。
#     有些专辑整体是 44.1k、有些整体 48k，这没问题。
#
#  4. 声道数必须一致（全立体声，或全单声道）。本工具不做声道转换，
#     同一批次里混用单声道与立体声会直接报错。
#
#
#  ┌────────────────────────────────────────────────────────────────────────┐
#  │  磁盘空间                                                              │
#  └────────────────────────────────────────────────────────────────────────┘
#
#      工作目录  约 = 源文件总大小 × 0.9  （MLP 缓存）
#      输出目录  约 = 源文件总大小 × 1.1  （ISO，未压缩的 AOB）
#
#  例：147 首约 9 GB 的 FLAC → 工作目录需 ~8 GB，输出目录需 ~8 GB。
#
# ============================================================================


# ---------------------------------------------------------------------------
# 1. 音源目录（必填，只读，不会被修改）
# ---------------------------------------------------------------------------
# 改成你自己的音源根目录（WSL 写法）。下面的值只是示例，必须改。
DVDA_SRC="/mnt/d/Music/MyAlbums"


# ---------------------------------------------------------------------------
# 2. ISO 输出目录（必填）
# ---------------------------------------------------------------------------
# 改成你自己的输出目录（WSL 写法）。下面的值只是示例，必须改。
DVDA_FINAL_DIR="/mnt/d/DVD_Output"


# ---------------------------------------------------------------------------
# 3. 工作目录（可选）
# ---------------------------------------------------------------------------
# 中间产物（manifest / MLP 缓存 / 临时目录 / ISO 暂存）的根目录。
DVDA_BUILD_DIR="/root/dvda-build"


# ---------------------------------------------------------------------------
# 4. 光盘标题（可选）
# ---------------------------------------------------------------------------
# 用途有两个：
#   · 刻录后的光盘卷标："{DVDA_TITLE} {序号}"，如 "My Album 1"、"My Album 2"
#     卷标建议 ≤ 30 字符（DVD 卷标上限 32）
#   · DVDA_ISO_PREFIX 未指定时，由它派生文件名前缀
#     （非字母数字的字符会替换成下划线）
DVDA_TITLE="My DVD-Audio"


# ---------------------------------------------------------------------------
# 5. ISO 文件名前缀（可选）
# ---------------------------------------------------------------------------
# 成品文件名为 "{前缀}_{序号}.iso"。
# 留空则由 DVDA_TITLE 自动派生。
DVDA_ISO_PREFIX=""


# ---------------------------------------------------------------------------
# 6. 分盘控制（可选）
# ---------------------------------------------------------------------------
# 期望的盘数上限。仅用于「内容是否放得下」的判断与提示，
# **不参与切分** —— 分盘一律「逐盘填满」（专辑不拆散，所以这是用最少盘数装下）。
#
# 若实际需要的盘数超过这个值，会在分盘结果里给出提示，但不会强行压缩分盘
# （强行均分反而可能多出一张几乎空的盘）。
# 设为 0 表示不检查。
DVDA_MAX_DISCS="2"

# 每个音频组最多几轨。DVD-Audio 协议上限 99，但 dvda-author 的 ATSI 表
# 缓冲固定 3 扇区（6144 字节、每轨约 52 字节），**超过约 70 轨会栈溢出**。
# 默认 64，不要设超过 70。
DVDA_GROUP_TRACK_LIMIT="64"

# 单张盘的容量上限（字节）。默认 4707319808 = 单层 DVD-5。
# 双层 DVD-9 可设为 8540123136。
DVDA_DISC_BYTES=""


# ---------------------------------------------------------------------------
# 6.5 MLP 来源（可选）
# ---------------------------------------------------------------------------
# ffmpeg   = 本工具链自己编码（默认）
# external = 用外部编码器（如 SurCode MLP）已经编好的 MLP，跳过编码阶段
#
# 选 external 时需同时设 DVDA_MLP_EXTERNAL_DIR，且目录结构要与音源一一对应：
#
#     音源：  <DVDA_SRC>/<专辑目录>/<曲名>.flac
#     外部：  <DVDA_MLP_EXTERNAL_DIR>/<专辑目录>/<曲名>.mlp
#
# （即去掉音源根目录前缀、只把扩展名换成 .mlp）
#
# 注意：外部编码器可能改采样率/位深（SurCode 会把全部曲目统一到 48000/24）。
# 本工具链以**实际探测到的 MLP 参数**为准来分组与分盘，不迷信 manifest，
# 并在参数与源不一致时给出提示。
DVDA_MLP_SOURCE="ffmpeg"
DVDA_MLP_EXTERNAL_DIR=""


# ---------------------------------------------------------------------------
# 7. 工具路径（可选，留空则用内置默认值）
# ---------------------------------------------------------------------------
# 带 24-bit MLP 支持的自编译 dvda-author（见 build_dvda_author_mlp.sh）
DVDA_AUTHOR=""

# patched mkisofs（需支持 -dvd-audio）
DVDA_MKISOFS=""

# ffmpeg / ffprobe。必须支持 mlp 编解码：
#     ffmpeg -hide_banner -encoders | grep mlp
DVDA_FFMPEG="ffmpeg"
DVDA_FFPROBE="ffprobe"

# dvda-author 源码目录（build_dvda_author_mlp.sh 用）
DVDA_AUTHOR_SRC=""
DVDA_AUTHOR_ORIG=""


# ============================================================================
#  以下内容通常不需要修改
# ============================================================================

# 解码完整性校验的容差（秒）
#   解码采样数比源声明少 超过 DVDA_LOSS_ERROR_S  → FAIL
#   采样数差异        超过 DVDA_LOSS_WARN_S       → WARN
DVDA_LOSS_ERROR_S="0.05"
DVDA_LOSS_WARN_S="0.005"

# Apple ALAC「未压缩帧缺 END 标记」自动修复
#   1 = 开启（推荐）；0 = 关闭，仅报告不修复
DVDA_ALAC_REPAIR="1"
